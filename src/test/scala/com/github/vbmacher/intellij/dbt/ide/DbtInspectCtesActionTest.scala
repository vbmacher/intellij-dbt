package com.github.vbmacher.intellij.dbt.ide

import com.intellij.openapi.ui.{TestDialog, TestDialogManager}
import com.intellij.xdebugger.XDebuggerManager
import org.junit.Assert._

final class DbtInspectCtesActionTest extends DbtTestCase {
  private def rejection(sql: String): String = {
    project()
    val file = configure("models/inspect.sql", sql + "<caret>")
    val action = new DbtModelRunLineMarker().getSlowInfo(file.findElementAt(0)).actions
      .find(_.isInstanceOf[DbtInspectCtesAction]).get
    var message = Option.empty[String]
    val previous = TestDialogManager.setTestDialog(new TestDialog {
      override def show(text: String): Int = {
        message = Some(text)
        0
      }
    })
    try {
      myFixture.testAction(action)
      await("The gutter action explains why inspection cannot open") { message.nonEmpty }
      assertFalse(getProject.getService(classOf[DbtRunner]).isRunning)
      assertTrue(XDebuggerManager.getInstance(getProject).getDebugSessions.isEmpty)
      message.get
    } finally TestDialogManager.setTestDialog(previous)
  }

  def testGutterReportsSqlAnalysisFailureInsteadOfSilentlyReturning(): Unit = {
    val text = rejection("with a as (select 1 as id)\nselect * from a where )")
    assertTrue(text, text.contains("Cannot inspect this model's CTEs."))
    assertTrue(text, text.contains("could not parse this model's SQL"))
    assertTrue(text, text.contains("line 2, column"))
    assertTrue(text, text.contains("No query was run."))
  }

  def testGutterExplainsWhenTheModelHasNoCtes(): Unit = {
    val text = rejection("select 1 as id")
    assertTrue(text, text.contains("no top-level CTEs"))
    assertTrue(text, text.contains("No query was run."))
  }

  def testGutterExplainsThatMacroGeneratedCtesRequireCompiledSql(): Unit = {
    val text = rejection("""{{ config(materialized='view') }}

{{ wms_stage_packaging_input(
    source('wms_raw', 'all_cma_pairwise_final_output_all_demo_combinations')
) }}""")
    assertTrue(text, text.contains("CTEs generated by macros cannot be stepped here"))
    assertTrue(text, text.contains("Open Compiled dbt SQL"))
    assertTrue(text, text.contains("No query was run."))
  }
}
